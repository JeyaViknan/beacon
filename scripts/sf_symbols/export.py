"""Export the SF Symbols Beacon uses into web/.symbols/sf.generated.ts (ADR 0016).

    ./scripts/export_sf_symbols.sh   # runs this with fontTools

Reads the names in web/src/symbols/names.ts, finds each one's code point in the SF Symbols
app's font (match.swift), and writes its outline as SVG path data. All symbols share one
square frame centred on their ink, so they keep their relative sizes, as SF Symbols do at one
point size. The output is for the iPhone app build only and is never committed: SF Symbols
are licensed for apps on Apple platforms.
"""

import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
NAMES_TS = ROOT / "web" / "src" / "symbols" / "names.ts"
OUT_DIR = ROOT / "web" / ".symbols"
MATCHER_SRC = Path(__file__).with_name("match.swift")

FRAME = 3072  # font units; 1.5 em, enough for the widest symbol Beacon uses
WEIGHT = 400  # regular
MAX_SCORE = 0.08  # mean per-cell difference above which a match is suspect (good: < 0.06)
MIN_MARGIN = (
    0.01  # a different glyph this close behind makes the match ambiguous (equal = same shape)
)


def symbol_names() -> list[str]:
    block = NAMES_TS.read_text().split("SYMBOL_NAMES = [", 1)[1].split("] as const", 1)[0]
    return re.findall(r'"([a-z0-9.]+)"', block)


def matcher() -> Path:
    binary = OUT_DIR / "match"
    if not binary.exists() or binary.stat().st_mtime < MATCHER_SRC.stat().st_mtime:
        swiftc = shutil.which("swiftc")
        if swiftc is None:
            sys.exit("swiftc not found: install Xcode's command line tools")
        # Our own source file and output path; no outside input reaches the command.
        subprocess.run([swiftc, "-O", str(MATCHER_SRC), "-o", str(binary)], check=True)  # noqa: S603
    return binary


def main(font_path: str) -> None:
    OUT_DIR.mkdir(exist_ok=True)
    names = symbol_names()
    # The matcher we just built, the font path from export_sf_symbols.sh, and names.ts.
    result = subprocess.run(  # noqa: S603
        [str(matcher()), font_path, *names], check=True, capture_output=True, text=True
    )
    found = json.loads(result.stdout)
    font = TTFont(font_path, lazy=True)
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet(location={"wght": WEIGHT})

    entries = []
    for name in names:
        hit = found[name]
        margin = hit["runnerUp"] - hit["score"]
        if hit["score"] > MAX_SCORE or 0 < margin < MIN_MARGIN:
            sys.exit(f"{name}: no clear match (score {hit['score']:.3f}, margin {margin:.3f})")
        glyph = glyphs[cmap[int(hit["cp"])]]
        bounds = BoundsPen(glyphs)
        glyph.draw(bounds)
        x_min, y_min, x_max, y_max = bounds.bounds
        if max(x_max - x_min, y_max - y_min) > FRAME:
            sys.exit(f"{name} is wider than the shared frame; raise FRAME")
        # Font outlines are y-up; SVG is y-down.
        svg = SVGPathPen(glyphs, ntos=lambda v: str(round(v)))
        glyph.draw(TransformPen(svg, (1, 0, 0, -1, 0, 0)))
        cx, cy = (x_min + x_max) / 2, -(y_min + y_max) / 2
        view_box = f"{round(cx - FRAME / 2)} {round(cy - FRAME / 2)} {FRAME} {FRAME}"
        entries.append(
            f'  "{name}": {{ viewBox: "{view_box}", body: \'<path d="{svg.getCommands()}"/>\' }},'
        )

    out = OUT_DIR / "sf.generated.ts"
    out.write_text(
        "// Generated by scripts/export_sf_symbols.sh from the SF Symbols app on this Mac.\n"
        "// Not committed: SF Symbols are licensed for apps on Apple platforms only (ADR 0016).\n"
        'import type { SymbolDef, SymbolName } from "../src/symbols/names";\n\n'
        "export const SYMBOLS: Record<SymbolName, SymbolDef> = {\n" + "\n".join(entries) + "\n};\n"
    )
    print(f"Exported {len(entries)} SF Symbols to {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main(sys.argv[1])
